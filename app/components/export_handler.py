"""Export functionality for the Legal Research Assistant.

Generates a Markdown document containing the query, answer, cited
sources with full metadata, confidence score, timestamp, and a legal
disclaimer. Offers the document via ``st.download_button``.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

import streamlit as st


def _build_source_block(source: dict, index: int) -> str:
    """Build a Markdown block for a single source."""
    metadata = source.get("metadata", source)
    lines: list[str] = [f"### Source {index}"]

    doc_type = metadata.get("doc_type", "unknown")
    lines.append(f"- **Type:** {doc_type.replace('_', ' ').title()}")

    case_name = metadata.get("case_name")
    if case_name:
        lines.append(f"- **Case:** {case_name}")

    act_name = metadata.get("act_name")
    if act_name:
        lines.append(f"- **Act:** {act_name}")

    section_number = metadata.get("section_number")
    if section_number:
        lines.append(f"- **Section:** {section_number}")

    citation = metadata.get("citation")
    if citation:
        lines.append(f"- **Citation:** {citation}")

    court = metadata.get("court")
    if court:
        lines.append(f"- **Court:** {court}")

    date = metadata.get("date")
    if date:
        lines.append(f"- **Date:** {date}")

    page_numbers = metadata.get("page_numbers", [])
    if page_numbers:
        lines.append(f"- **Pages:** {', '.join(str(p) for p in page_numbers)}")

    paragraph_numbers = metadata.get("paragraph_numbers", [])
    if paragraph_numbers:
        lines.append(
            f"- **Paragraphs:** {', '.join(str(p) for p in paragraph_numbers)}"
        )

    text = source.get("text", "")
    if text:
        lines.append("")
        lines.append("**Excerpt:**")
        lines.append("")
        lines.append(f"> {text[:2000]}")

    return "\n".join(lines)


def _generate_markdown(
    query: str,
    answer: str,
    sources: list[dict],
    confidence: Any = None,
) -> str:
    """Produce the full Markdown export document."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    sections: list[str] = [
        "# Nyaya - Legal Research Export",
        "",
        f"**Generated:** {now}",
        "",
        "---",
        "",
        "## Query",
        "",
        query,
        "",
        "## Answer",
        "",
        answer,
        "",
    ]

    if confidence is not None:
        if isinstance(confidence, (int, float)):
            score = float(confidence)
        elif isinstance(confidence, dict):
            score = float(confidence.get("overall_score", 0.0))
        else:
            score = float(getattr(confidence, "overall_score", 0.0))
        pct = int(max(0.0, min(1.0, score)) * 100)
        sections.append(f"**Confidence Score:** {pct}%")
        sections.append("")

    if sources:
        sections.append("---")
        sections.append("")
        sections.append("## Cited Sources")
        sections.append("")
        for idx, src in enumerate(sources, start=1):
            source_idx = src.get("source_index", idx) if isinstance(src, dict) else idx
            sections.append(_build_source_block(src, source_idx))
            sections.append("")

    sections.extend([
        "---",
        "",
        "## Disclaimer",
        "",
        (
            "This document is generated by Nyaya - Legal Research Assistant "
            "for **research purposes only**. The information provided should not "
            "be treated as legal advice. Please verify all references against "
            "original documents and consult a qualified advocate before relying "
            "on any legal information contained herein."
        ),
    ])

    return "\n".join(sections)


def render_export_button(
    query: str,
    answer: str,
    sources: list[dict],
    confidence: Any = None,
) -> None:
    """Render a download button that exports the answer as Markdown.

    Parameters
    ----------
    query:
        The user's original question.
    answer:
        The generated answer text.
    sources:
        List of source dicts with ``"text"`` and ``"metadata"``.
    confidence:
        Optional confidence score (float, dict, or object).
    """
    md_content = _generate_markdown(query, answer, sources, confidence)

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    filename = f"nyaya_research_{timestamp}.md"

    st.download_button(
        label="Export as Markdown",
        data=md_content,
        file_name=filename,
        mime="text/markdown",
        use_container_width=True,
    )
